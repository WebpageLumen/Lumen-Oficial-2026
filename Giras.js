const banderas = { es: "https://flagcdn.com/w80/es.png", en: "https://flagcdn.com/w80/gb.png" };

// ===== MAPA DE IMÁGENES POR IDIOMA =====
const imagenesIlustrativas = {
  es: {
    p1: "Imagenes/p1.png",
    p2: "Imagenes/p2.png"
  },
  en: {
    p1: "Imagenes/p1e.png",
    p2: "Imagenes/p2e.png"
  }
};

function aplicarIdioma(idioma) {
  const dic = traducciones[idioma];
  if (!dic) return;

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const clave = el.getAttribute('data-i18n');
    if (dic[clave] !== undefined) el.textContent = dic[clave];
  });

  // Imágenes ilustrativas (p1 y p2)
const imagenesMap = imagenesIlustrativas[idioma] || imagenesIlustrativas.es;

// Actualizar imagen p1 (primera imagen ilustrativa)
const imgP1 = document.querySelector('.intro-imagen img[src*="p1"]');
if (imgP1 && imagenesMap.p1) {
  imgP1.src = imagenesMap.p1;
}

// Actualizar imagen p2 (segunda imagen ilustrativa)
const imgP2 = document.querySelector('.intro-imagen img[src*="p2"]');
if (imgP2 && imagenesMap.p2) {
  imgP2.src = imagenesMap.p2;
}

  document.documentElement.setAttribute('lang', idioma);

  const langLabel = document.getElementById('langLabel');
  const langFlag = document.getElementById('langFlag');
  if (langLabel) langLabel.textContent = idioma.toUpperCase();
  if (langFlag) langFlag.src = banderas[idioma];

  document.querySelectorAll('.lang-option').forEach((op) => {
    op.classList.toggle('selected', op.getAttribute('data-lang') === idioma);
  });

  try { localStorage.setItem('lumen-lang', idioma); } catch (e) {}
}

const langBtn = document.getElementById('langBtn');
const langDropdown = document.getElementById('langDropdown');

if (langBtn && langDropdown) {
  langBtn.addEventListener('click', (e) => {
    e.stopPropagation();
    const abierto = langDropdown.classList.toggle('open');
    langBtn.setAttribute('aria-expanded', abierto ? 'true' : 'false');
  });

  document.querySelectorAll('.lang-option').forEach((opcion) => {
    opcion.addEventListener('click', () => {
      const idioma = opcion.getAttribute('data-lang');
      aplicarIdioma(idioma);
      langDropdown.classList.remove('open');
      langBtn.setAttribute('aria-expanded', 'false');
    });
  });

  document.addEventListener('click', () => {
    langDropdown.classList.remove('open');
    langBtn.setAttribute('aria-expanded', 'false');
  });
}

// Aplica el idioma guardado (o español por defecto) al cargar la página
(function iniciarIdioma() {
  let guardado = 'es';
  try { guardado = localStorage.getItem('lumen-lang') || 'es'; } catch (e) {}
  aplicarIdioma(guardado);
})();

