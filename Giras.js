// ===== Carrusel de giras: la flecha despliega/oculta 6 tarjetas extra =====


const carrusel = document.getElementById("carrusel");
const flechaVerMas = document.getElementById("flechaVerMas");

let abierto = false;

flechaVerMas.addEventListener("click", () => {

    abierto = !abierto;

    carrusel.classList.toggle("mostrar-mas");

    flechaVerMas.classList.toggle("girado", abierto);

    flechaVerMas.setAttribute("aria-expanded", abierto);

    flechaVerMas.setAttribute(
        "aria-label",
        abierto ? "Ver menos giras" : "Ver más giras"
    );

    if (abierto) {
    carrusel.style.justifyContent = "flex-start";
    carrusel.style.overflowX = "auto";
} else {
    carrusel.scrollLeft = 0;
    carrusel.style.justifyContent = "center";
    carrusel.style.overflowX = "hidden";
}

});


document.querySelectorAll('.tarjeta-gira').forEach((tarjeta) => {
  tarjeta.addEventListener('click', (e) => {
    if (e.target.classList.contains('tarjeta-cta')) return;
    const destino = tarjeta.getAttribute('data-destino');
    if (destino) window.location.href = destino;
  });
});
